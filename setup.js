// Writes Espanso text-expander files so SQL shortcuts work in:
//   - SQL Server Management Studio: the T-SQL set
//   - Microsoft Fabric notebooks in Chrome: the Spark SQL / PySpark set (spark.json)
// Each set is switched on only in its own app, so nothing expands while typing elsewhere.
//
// The T-SQL set comes from your SQL Shortcuts list in VS Code if you use that extension
// (https://github.com/chaya-abramovitz/vscode-sql-shortcuts), otherwise from tsql/tsql.json.
//
// Usage: node setup.js [espanso folder]     (default: %APPDATA%\espanso)
// Espanso reloads by itself when the files change.

const fs = require('fs');
const path = require('path');

const root = __dirname;
const appData = process.env.APPDATA || path.join(require('os').homedir(), 'AppData', 'Roaming');
const outDir = process.argv[2] || path.join(appData, 'espanso');
const vscodeList = path.join(appData, 'Code', 'User', 'globalStorage', 'chaya-local.sql-shortcuts', 'shortcuts.json');
const tsqlDefaults = path.join(root, 'tsql', 'tsql.json');
const tsqlFirstRelease = path.join(root, 'tsql', 'defaults-v1.json');

// Shortcuts that are also common words or table aliases; in Espanso they need a ; in front (;cte).
const WORDLIKE = new Set(['is', 'go', 'use', 'at', 'ex', 'rn', 'cte', 'ct', 'dt', 'pk', 'fk', 'j', 'as', 'on', 'in', 'or', 'to', 'by']);

const STOP = /\$\{(\d+):((?:\\.|[^{}$\\])*)\}|\$\{(\d+)\}|\$(\d+)/g;
const unescape = s => s.replace(/\\([\\$}])/g, '$1');

// VS Code snippet body -> Espanso text with a single $|$ cursor at the first spot to fill in.
function toEspanso(body) {
  const stops = [...body.matchAll(STOP)].map(m => ({ m, n: Number(m[1] || m[3] || m[4]), text: m[2] }));
  const numbered = stops.filter(s => s.n > 0).map(s => s.n);
  const target = numbered.length ? Math.min(...numbered) : 0;
  let out = '';
  let last = 0;
  let placed = false;
  for (const s of stops) {
    out += unescape(body.slice(last, s.m.index));
    last = s.m.index + s.m[0].length;
    const text = s.text !== undefined ? unescape(s.text) : '';
    if (!placed && s.n === target) { out += '$|$' + text; placed = true; }
    else out += text;
  }
  out += unescape(body.slice(last));
  return placed ? out : out + '$|$';
}

function readShortcuts(file) {
  const json = JSON.parse(fs.readFileSync(file, 'utf8').replace(/^﻿/, ''));
  const list = [];
  for (const [name, s] of Object.entries(json)) {
    if (!s || !s.body) continue;
    const prefixes = Array.isArray(s.prefix) ? s.prefix : [s.prefix || name];
    const body = Array.isArray(s.body) ? s.body.join('\n') : String(s.body);
    for (const p of prefixes) if (/^[A-Za-z][A-Za-z0-9_]*$/.test(p)) list.push({ prefix: p, description: s.description || p, body });
  }
  return list;
}

function matchesYaml(list, source) {
  const lines = [
    `# Generated by setup.js from ${source}.`,
    '# To change these, edit the source and run setup.js again.',
    'matches:'
  ];
  for (const s of list) {
    const replace = toEspanso(s.body);
    if (replace.includes('{{')) continue; // Espanso would read {{...}} as a variable
    const wordlike = WORDLIKE.has(s.prefix.toLowerCase());
    lines.push(`  - trigger: ${JSON.stringify(wordlike ? ';' + s.prefix : s.prefix)}`);
    lines.push(`    replace: ${JSON.stringify(replace)}`);
    if (!wordlike) lines.push('    word: true');
    lines.push(`    label: ${JSON.stringify((wordlike ? ';' : '') + s.prefix + ': ' + s.description)}`);
  }
  return lines.join('\n') + '\n';
}

function write(rel, text, onlyIfMissing) {
  const file = path.join(outDir, rel);
  if (onlyIfMissing && fs.existsSync(file)) return;
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, text, 'utf8');
  console.log('wrote', file);
}

// T-SQL set: your VS Code list if there is one, plus newer defaults it hasn't received yet
// (VS Code adds those on its next start). Missing shortcuts from the first release were
// deleted on purpose, so they stay out.
const fromVsCode = fs.existsSync(vscodeList);
const tsql = readShortcuts(fromVsCode ? vscodeList : tsqlDefaults);
if (fromVsCode) {
  const have = new Set(tsql.map(s => s.prefix.toLowerCase()));
  const original = new Set(readShortcuts(tsqlFirstRelease).map(s => s.prefix.toLowerCase()));
  for (const s of readShortcuts(tsqlDefaults)) {
    if (!have.has(s.prefix.toLowerCase()) && !original.has(s.prefix.toLowerCase())) tsql.push(s);
  }
}
const spark = readShortcuts(path.join(root, 'spark.json'));

// Files whose names start with _ are not loaded everywhere; the app rules below pull them in.
write(path.join('match', '_tsql.yml'), matchesYaml(tsql, fromVsCode ? 'your SQL Shortcuts list in VS Code' : 'tsql/tsql.json'));
write(path.join('match', '_spark.yml'), matchesYaml(spark, 'spark.json'));

write(path.join('config', 'ssms.yml'), [
  '# T-SQL shortcuts, only in SQL Server Management Studio.',
  'filter_exec: "(?i)ssms\\\\.exe"',
  'extra_includes:',
  '  - "../match/_tsql.yml"',
  ''
].join('\n'));

write(path.join('config', 'fabric.yml'), [
  '# Spark SQL / PySpark shortcuts, only in Microsoft Fabric tabs in Chrome.',
  '# Fabric titles its pages "<item> - Fabric" or "<item> - Power BI".',
  'filter_exec: "(?i)chrome\\\\.exe"',
  'filter_title: "(Fabric|Power BI) - Google Chrome$"',
  'extra_includes:',
  '  - "../match/_spark.yml"',
  ''
].join('\n'));

// Espanso's own starting files, only on a fresh setup
write(path.join('config', 'default.yml'), '# Espanso settings that apply everywhere. See https://espanso.org/docs/configuration/options/\n', true);
write(path.join('match', 'base.yml'), '# Shortcuts that work in every app. The SQL ones are in _tsql.yml and _spark.yml.\nmatches: []\n', true);

console.log(`T-SQL shortcuts: ${tsql.length}, Spark shortcuts: ${spark.length}`);
